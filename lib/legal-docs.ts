/** docs/legal/*.md로 내보낼 마크다운 (scripts/check-pay-rules가 문서와 같은지 확인) */
export function legalMarkdown(d: LegalDoc) {
  const cell = (s: string) => s.replace(/\|/g, '\\|');
  const out = [`# ${d.title}`, '', `- 판: ${d.version}`, `- 시행일: ${d.effective}`, ...(d.reviewed ? [] : ['- 상태: **법률 검토 전 초안**']), '', ...operatorBlock().map(l => `> ${l}`), ''];
  for (const s of d.sections) {
    out.push(`## ${s.title}`, '');
    for (const b of s.body) {
      if (typeof b === 'string') out.push(b, '');
      else out.push(`| ${b.rows[0].map(cell).join(' | ')} |`, `|${b.rows[0].map(() => '---').join('|')}|`, ...b.rows.slice(1).map(r => `| ${r.map(cell).join(' | ')} |`), '');
    }
  }
  out.push('## 이전 판', '', ...d.history.map(h => `- ${h.version} (시행 ${h.effective}): ${h.note}`), '', '<!-- 이 파일은 lib/legal-docs.ts에서 만든다. 직접 고치지 말고 node scripts/legal-md.mjs로 다시 만든다. -->', '');
  return out.join('\n');
}
