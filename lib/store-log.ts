export function tempIssue(t: {name: string; value: number; type: string}) {
  if (t.type === '냉장' && (t.value < 0 || t.value > 5)) return `${t.name} ${t.value}℃(냉장 0~5℃)`;
  if (t.type === '냉동' && t.value > -18) return `${t.name} ${t.value}℃(냉동 -18℃ 이하)`;
  return '';
}
