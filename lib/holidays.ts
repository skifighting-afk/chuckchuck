// 작업 025: 휴일 달력. 5명 이상 사업장은 관공서 공휴일이 유급휴일(근로기준법 제55조②, 시행령 제30조②).
// 근로자의 날(5월 1일)은 사업장 규모와 상관없이 유급휴일(근로자의날 제정에 관한 법률).
// 2026년 목록: 관공서의 공휴일에 관한 규정 + 대체공휴일 + 임시공휴일(6/3 지방선거) — 2026-10-05 확인(위키트리 2025.12 정리 기사 대조).
export const PUBLIC_HOLIDAYS: Record<number, [string, string][]> = {
  2026: [
    ['2026-01-01', '신정'], ['2026-02-16', '설날 연휴'], ['2026-02-17', '설날'], ['2026-02-18', '설날 연휴'],
    ['2026-03-01', '3·1절'], ['2026-03-02', '대체공휴일(3·1절)'], ['2026-05-05', '어린이날'], ['2026-05-24', '부처님오신날'], ['2026-05-25', '대체공휴일(부처님오신날)'],
    ['2026-06-03', '전국동시지방선거'], ['2026-06-06', '현충일'], ['2026-07-17', '제헌절'], ['2026-08-15', '광복절'], ['2026-08-17', '대체공휴일(광복절)'],
    ['2026-09-24', '추석 연휴'], ['2026-09-25', '추석'], ['2026-09-26', '추석 연휴'], ['2026-10-03', '개천절'], ['2026-10-05', '대체공휴일(개천절)'],
    ['2026-10-09', '한글날'], ['2026-12-25', '성탄절'],
  ],
};
export const hasHolidaysFor = (year: number) => !!PUBLIC_HOLIDAYS[year];
/** 그해 휴일(날짜 → 이름). fivePlus면 관공서 공휴일 포함, 근로자의 날은 항상. */
export function holidaysFor(year: number, fivePlus: boolean) {
  const m = new Map<string, string>();
  if (fivePlus) for (const [d, n] of PUBLIC_HOLIDAYS[year] || []) m.set(d, n);
  m.set(`${year}-05-01`, '근로자의 날');
  return m;
}
