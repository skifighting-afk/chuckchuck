import assert from 'node:assert/strict';
import {personalTeam} from '../lib/personal-team.ts';
const display=await import('../lib/attendance-display.ts').catch(e=>{if(e.code==='ERR_MODULE_NOT_FOUND')return {};throw e});
assert.equal(typeof display.attendanceEvidence,'function','shared attendance explanation is available');
const {attendanceStatusLabel,attendanceEvidence}=display;
const personal=personalTeam({store:{},branches:[{id:'b'}],employees:[{id:'e',branchId:'b'},{id:'other',branchId:'b'}],shifts:[],attendance:[],adjustments:{},payrollRuns:{},requests:[],settings:{attendanceTolerance:'strict'},approvedLeaves:[{employeeId:'e',start:'2026-10-12',end:'2026-10-12',reason:'private'},{employeeId:'other',start:'2026-10-12',end:'2026-10-12'}]},'e');
assert.equal(personal.settings.attendanceTolerance,'strict','staff receives the same current attendance tolerance');
assert.deepEqual(personal.approvedLeaves,[{employeeId:'e',start:'2026-10-12',end:'2026-10-12'}],'only own leave dates, no colleague or reason data');
const shift={id:'s',employeeId:'e',date:'2026-10-12',start:'17:00',end:'22:00'};
const row=(statuses,records=[],s=shift)=>({key:'s',employeeId:'e',date:shift.date,shift:s,records,statuses});
const record={id:'a',employeeId:'e',start:'2026-10-12T08:06:00Z',end:'2026-10-12T12:58:00Z'};
assert.equal(attendanceStatusLabel({kind:'결근'}),'기록 누락 확인');
assert.equal(attendanceStatusLabel({kind:'미출근',minutes:6}),'출근 기록 대기');
assert.equal(attendanceStatusLabel({kind:'지각',minutes:6}),'지각 6분');
assert.match(attendanceEvidence(row([{kind:'결근'}]),5),/기록이 없어요.*결근 여부.*확인/);
assert.match(attendanceEvidence(row([{kind:'휴가'}]),5),/승인된 휴가/);
assert.match(attendanceEvidence(row([{kind:'출근 전'}]),5),/예정 시각.*허용 범위/);
const late=attendanceEvidence(row([{kind:'지각',minutes:6}],[record]),5);
assert.match(late,/예정 17:00.*출근 17:06.*6분 늦음.*현재 허용 5분/);
assert.match(late,/예정 22:00.*퇴근 21:58.*2분 빠름/);
assert.match(attendanceEvidence(row([{kind:'지각',minutes:5}],[{...record,start:'2026-10-12T08:05:10Z'}]),5),/5분 10초 늦음/);
assert.match(attendanceEvidence(row([{kind:'정상'}],[{...record,start:'2026-10-12T08:01:00Z'}]),5),/1분 늦음.*지각·조퇴 표시 없음/);
const extended=attendanceEvidence(row([{kind:'정상'}],[{...record,start:'2026-10-12T07:00:00Z',end:'2026-10-12T14:00:00Z'}]),5);
assert.match(extended,/60분 빠름.*60분 늦음.*지각·조퇴 표시 없음/);
assert.doesNotMatch(extended,/차이는 허용 범위 안/);
assert.match(attendanceEvidence(row([{kind:'지각',minutes:5}],[{...record,start:'2026-10-12T08:05:00.500Z'}]),5),/5분 0.5초 늦음/);
assert.match(attendanceEvidence(row([{kind:'지각',minutes:0}],[{...record,start:'2026-10-12T08:00:00.500Z'}]),0),/0.5초 늦음/);
assert.match(attendanceEvidence(row([{kind:'조퇴',minutes:5}],[{...record,end:'2026-10-12T12:54:59.500Z'}]),5),/5분 0.5초 빠름/);
const night={...shift,start:'22:00',end:'02:00'};
assert.match(attendanceEvidence(row([{kind:'정상'}],[{...record,start:'2026-10-12T13:00:00Z',end:'2026-10-12T17:00:00Z'}],night),0),/다음 날 02:00.*예정과 같음/);
assert.match(attendanceEvidence(row([{kind:'미퇴근'}],[{...record,end:null}]),5),/퇴근 기록 없음.*확인/);
assert.match(attendanceEvidence(row([{kind:'예정 외'}],[record],null),5),/근무표 밖 기록/);
assert.match(attendanceEvidence(row([{kind:'정상'}],[{...record,start:'2026-10-12T08:00:00Z',end:'2026-10-12T10:00:00Z'},{...record,id:'b',start:'2026-10-12T11:00:00Z',end:'2026-10-12T13:00:00Z'}]),5),/기록 2건.*첫 출근.*마지막 퇴근/);
console.log('PASS: missing records are not confirmed absence; shared precise attendance evidence.');
