import assert from 'node:assert/strict';
import {taskGroups,rememberPage,recordVisitedPage} from '../lib/task-navigation.ts';
const allowed=['홈','직원 관리','출퇴근 기록','근무 스케줄','급여·명세서','근로계약서','퇴직금 확인','전송함','휴가·공지','매장 매뉴얼','인건비 리포트','매장 관리·비교','설정','근로기준 안내'];
const groups=taskGroups(allowed),all=groups.flatMap(g=>g.pages);
assert.equal(new Set(all).size,allowed.length);assert.deepEqual([...all].sort(),[...allowed].sort());
assert.deepEqual(taskGroups(['홈','근무 스케줄']).flatMap(g=>g.pages),['홈','근무 스케줄'],'never add a page beyond the supplied permission set');
assert(groups.every(g=>g.pages.length));
assert.deepEqual(rememberPage(['설정','근무 스케줄','설정','unknown'],'급여·명세서',allowed),['급여·명세서','설정','근무 스케줄']);
assert.deepEqual(rememberPage(['설정'],'홈',allowed),['설정']);
assert.deepEqual(rememberPage(['설정'],'unknown',allowed),['설정']);
assert.deepEqual(rememberPage(['설정','근무 스케줄','급여·명세서'],'근무 스케줄',allowed),['근무 스케줄','설정','급여·명세서']);
const saved=new Map(),storage={getItem:key=>saved.get(key)||null,setItem:(key,value)=>saved.set(key,value)};
recordVisitedPage(storage,'owner-a:branch-a','근무 스케줄',allowed);
recordVisitedPage(storage,'owner-a:branch-a','출퇴근 기록',allowed);
assert.deepEqual(recordVisitedPage(storage,'owner-a:branch-a','홈',allowed),['출퇴근 기록','근무 스케줄'],'closed drawer visits remain available on Home');
assert.deepEqual(recordVisitedPage(storage,'owner-b:branch-a','홈',allowed),[],'another account has separate history');
assert.deepEqual(recordVisitedPage(storage,'owner-a:branch-b','홈',allowed),[],'another branch has separate history');
saved.set('cheok-recent-pages:owner-c','not json');assert.deepEqual(recordVisitedPage(storage,'owner-c','설정',allowed),['설정']);
console.log('PASS: all permitted task pages appear exactly once; recent pages are valid, unique and capped at three.');
