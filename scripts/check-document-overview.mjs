import assert from 'node:assert/strict';
import {documentOverview} from '../lib/document-overview.ts';
const employees=[{id:'a',name:'민지',status:'재직',contract:{status:'작성 중'}},{id:'b',name:'준호',status:'재직',contract:{status:'체결 완료'}},{id:'c',name:'퇴사자',status:'퇴사',contract:{status:'체결 완료'}}];
const contracts=[{employeeId:'a',id:'new',status:'waiting'}];
const docs=[{employee_id:'a',run_key:'2026-10:other',revision:2,state:'current',activity:{viewed_at:'now'}},{employee_id:'a',run_key:'2026-10:main',revision:1,state:'replaced'},{employee_id:'b',run_key:'2026-10:main',revision:1,state:'current',activity:{viewed_at:'now'}}];
let rows=documentOverview(employees,contracts,docs,'2026-10:main',true);
assert.equal(rows.length,2,'retired employees excluded');
assert.equal(rows[0].contract.label,'직원 서명 대기');
assert.equal(rows[0].payslip.label,'수정본 전달 필요','other branch document cannot satisfy delivery');
assert.equal(rows[0].needsAction,true);
assert.equal(rows[1].contract.label,'서면 체결 기록','paper record does not claim electronic signatures');
assert.equal(rows[1].payslip.label,'직원 확인함');
rows=documentOverview(employees,[],[],'2026-10:main',false);
assert.equal(rows[0].payslip.label,'급여 확정 후 전달');
rows=documentOverview(employees,null,null,'2026-10:main',true);
assert.equal(rows[0].contract.label,'상태 확인 필요','failed load must not become missing contract');
assert.equal(rows[0].payslip.label,'상태 확인 필요');
rows=documentOverview(employees,[{employeeId:'a',id:'x',status:'signed',changed:true}],[],'2026-10:main',true);
assert.equal(rows[0].contract.label,'조건 변경 확인');
rows=documentOverview(employees,[{employeeId:'a',id:'x',status:'waiting',changed:true}],[],'2026-10:main',true);
assert.equal(rows[0].contract.label,'조건 변경 · 재요청 필요');
console.log('PASS: employee document overview isolates branch/revision, paper/electronic, retired and unknown states.');
